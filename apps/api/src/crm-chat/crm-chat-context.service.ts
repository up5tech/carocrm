import { Injectable } from '@nestjs/common';

/**
 * Phase 19-CHAT.8 — context selection and citation reauthorization
 * (PLAN_Phase_19_CRM_Chat.md §10, §17 `19-CHAT.8`).
 *
 * This service ensures that:
 * 1. Context references sent to AIAgents are validated for format
 * 2. Citations returned by the model are checked for safe routes
 * 3. The model cannot inject arbitrary hyperlinks as trusted CRM citations
 *
 * Actual record-level authorization is enforced by AIAgents' CRM query tools, which already
 * apply ACL before returning any data. This service focuses on route safety and format validation.
 */

export interface ContextRef {
  readonly entity: string;
  readonly id: string;
}

export interface ValidatedContextRef extends ContextRef {
  readonly valid: boolean;
  readonly reason?: string | undefined;
}

export interface CitationSource {
  readonly sourceType: 'crm_record' | 'query_result' | 'report' | 'help_document' | 'approved_external_source';
  readonly sourceId?: string | undefined;
  readonly entity?: string | undefined;
  readonly displayLabel: string;
  readonly safeRoute?: string | undefined;
}

export interface ReauthorizedCitation extends CitationSource {
  readonly accessible: boolean;
  readonly resolvedRoute?: string | undefined;
  readonly reason?: string | undefined;
}

// Safe entity name pattern: alphanumeric, hyphens, underscores only
const ENTITY_NAME_RE = /^[a-zA-Z][a-zA-Z0-9_-]{0,119}$/;
// Safe ID pattern: no path traversal or special chars
const RECORD_ID_RE = /^[a-zA-Z0-9_-]{1,120}$/;

@Injectable()
export class CRMChatContextService {
  constructor() {}

  /**
   * Validate context reference format before sending to AIAgents. Does not check actual record
   * existence - that's done by AIAgents' CRM tools with proper ACL enforcement.
   */
  validateContextRef(ref: ContextRef): ValidatedContextRef {
    // Validate entity name format
    if (!ENTITY_NAME_RE.test(ref.entity)) {
      return {
        ...ref,
        valid: false,
        reason: 'Invalid entity name format.',
      };
    }

    // Validate record ID format
    if (!RECORD_ID_RE.test(ref.id)) {
      return {
        ...ref,
        valid: false,
        reason: 'Invalid record ID format.',
      };
    }

    return {
      ...ref,
      valid: true,
    };
  }

  /**
   * Validate multiple context refs. Returns only valid ones.
   */
  validateContextRefs(refs: readonly ContextRef[]): readonly ValidatedContextRef[] {
    return refs.map((ref) => this.validateContextRef(ref));
  }

  /**
   * Reauthorize a citation source before rendering. Validates that the route is safe and was
   * generated by trusted server code, not injected by the model.
   */
  reauthorizeCitation(citation: CitationSource): ReauthorizedCitation {
    // Non-CRM sources don't need route validation
    if (citation.sourceType !== 'crm_record') {
      return {
        ...citation,
        accessible: true,
        resolvedRoute: citation.safeRoute,
      };
    }

    // For CRM records, validate that we have required fields
    if (!citation.entity || !citation.sourceId) {
      return {
        ...citation,
        accessible: false,
        reason: 'Missing entity or source ID for CRM citation.',
      };
    }

    // Validate entity and ID format
    if (!ENTITY_NAME_RE.test(citation.entity)) {
      return {
        ...citation,
        accessible: false,
        reason: 'Invalid entity name in citation.',
      };
    }

    if (!RECORD_ID_RE.test(citation.sourceId)) {
      return {
        ...citation,
        accessible: false,
        reason: 'Invalid record ID in citation.',
      };
    }

    // Build a trusted route using server-side builder (never trust client-provided routes)
    const resolvedRoute = this.buildEntityRoute(citation.entity, citation.sourceId);

    return {
      ...citation,
      accessible: true,
      resolvedRoute,
    };
  }

  /**
   * Reauthorize multiple citations in parallel.
   */
  reauthorizeCitations(citations: readonly CitationSource[]): readonly ReauthorizedCitation[] {
    return citations.map((c) => this.reauthorizeCitation(c));
  }

  /**
   * Build a trusted route for an entity record. Uses server-side route builder, never trusts
   * client-provided URLs.
   */
  private buildEntityRoute(entity: string, id: string): string {
    // Use the standard CaroCRM route pattern with proper encoding
    return `/entity/${encodeURIComponent(entity)}/${encodeURIComponent(id)}`;
  }
}
